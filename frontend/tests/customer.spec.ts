import { expect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { mkdir } from 'node:fs/promises';

test('nasabah menyimpan profil dan draf, memulihkan respons terputus, lalu menghapus draf dengan konfirmasi', async ({ page }) => {
	const email = `draft-${randomUUID()}@example.test`;
	const password = randomUUID();
	const identity = '000' + Date.now().toString();
	await page.goto('/');
	await expect(page.getByText('Belum masuk. Silakan gunakan akun Anda.')).toBeVisible();
	await page.getByRole('button', { name: 'Buat akun', exact: true }).click();
	await page.getByLabel('Nama lengkap').fill('Nasabah Draf Fiktif');
	await page.getByLabel('Email', { exact: true }).fill(email);
	await page.getByLabel('Kata sandi', { exact: true }).fill(password);
	await page.getByLabel('Konfirmasi kata sandi').fill(password);
	await page.getByRole('button', { name: 'Daftar akun', exact: true }).click();
	await expect(page.getByText('Pendaftaran berhasil. Silakan masuk.')).toBeVisible();
	await page.getByLabel('Kata sandi', { exact: true }).fill(password);
	await page.getByRole('button', { name: 'Masuk', exact: true }).click();
	await page.getByRole('link', { name: 'Buka ruang nasabah' }).click();
	await expect(page).toHaveTitle('Ruang Nasabah | Lendara');
	await expect(page.getByRole('button', { name: 'Simpan profil', exact: true })).toBeEnabled();
	await page.getByLabel('NIK fiktif', { exact: true }).fill(identity);
	await page.getByLabel('Tanggal lahir', { exact: true }).fill('1995-01-15');
	await page.getByLabel('Jenis pekerjaan', { exact: true }).fill('Karyawan fiktif');
	await page.getByLabel('Tempat bekerja', { exact: true }).fill('Perusahaan Demonstrasi');
	await page.getByLabel('Lama bekerja (bulan)', { exact: true }).fill('24');
	await page.getByLabel('Alamat fiktif', { exact: true }).fill('Alamat fiktif untuk pengujian');
	const profileSaved = page.waitForResponse((r) => r.url().endsWith('/customer/profile') && r.request().method() === 'PATCH');
	await page.getByRole('button', { name: 'Simpan profil', exact: true }).click();
	expect((await profileSaved).status()).toBe(200);
	await expect(page.getByText('Profil tersimpan. Data pengiriman sebelumnya tetap dipertahankan.')).toBeVisible();

	const created = page.waitForResponse((r) => r.url().endsWith('/applications') && r.request().method() === 'POST');
	await page.getByRole('button', { name: 'Buat draf pengajuan' }).click();
	const createdResponse = await created;
	expect(createdResponse.status()).toBe(201);
	const application = (await createdResponse.json()).data;
	const id: number = application.id;
	expect(application.loan_amount).toBeNull();
	await expect(page.getByRole('button', { name: 'Simpan draf', exact: true })).toBeEnabled();
	await expect(page.getByRole('button', { name: 'Buat draf pengajuan' })).toHaveCount(0);
	await page.getByLabel('Jumlah pinjaman (Rp)', { exact: true }).fill('20000000.01');
	await page.getByLabel('Pendapatan per bulan (Rp)', { exact: true }).fill('8000000');
	await page.getByLabel('Pengeluaran di luar cicilan (Rp)', { exact: true }).fill('3000000');
	await page.getByLabel('Cicilan berjalan per bulan (Rp)', { exact: true }).fill('0');
	await page.getByLabel('Tenor (bulan)', { exact: true }).fill('12');
	await page.getByLabel('Tujuan pinjaman', { exact: true }).fill('Keperluan demonstrasi akademik');
	const draftSaved = page.waitForResponse((r) => r.url().endsWith(`/applications/${id}`) && r.request().method() === 'PATCH');
	await page.getByRole('button', { name: 'Simpan draf', exact: true }).click();
	const savedResponse = await draftSaved;
	expect(savedResponse.status()).toBe(200);
	expect((await savedResponse.json()).data.loan_amount).toBe('20000000.01');
	await expect(page.getByText('Draf tersimpan. Pengajuan belum dikirim untuk ditinjau.')).toBeVisible();
	await page.reload();
	await expect(page.getByLabel('Jumlah pinjaman (Rp)', { exact: true })).toHaveValue('20000000.01');
	await expect(page.getByLabel('NIK fiktif', { exact: true })).toHaveValue(identity);
	await expect(page.getByRole('button', { name: 'Simpan draf', exact: true })).toBeEnabled();
	await page.getByLabel('Jumlah pinjaman (Rp)', { exact: true }).fill('1e3');
	await page.getByRole('button', { name: 'Simpan draf', exact: true }).click();
	await expect(page.getByLabel('Jumlah pinjaman (Rp)', { exact: true })).toHaveAttribute('aria-invalid', 'true');
	await page.getByLabel('Jumlah pinjaman (Rp)', { exact: true }).fill('20000000.01');
	await page.getByLabel('Tenor (bulan)', { exact: true }).fill('abc');
	await page.getByRole('button', { name: 'Simpan draf', exact: true }).click();
	await expect(page.getByLabel('Tenor (bulan)', { exact: true })).toHaveAttribute('aria-invalid', 'true');
	await page.getByLabel('Tenor (bulan)', { exact: true }).fill('12');
	await page.getByLabel('Tujuan pinjaman', { exact: true }).fill('Tersimpan walau respons terputus');
	let patches = 0;
	await page.route(`**/api/v1/applications/${id}`, async (route) => {
		patches++;
		const response = await route.fetch();
		expect(response.status()).toBe(200);
		await route.abort();
	}, { times: 1 });
	await page.getByRole('button', { name: 'Simpan draf', exact: true }).click();
	await expect(page.getByRole('alert')).toContainText('Periksa sesi sebelum mengirim ulang');
	await expect(page.getByRole('button', { name: 'Simpan draf', exact: true })).toBeDisabled();
	expect(patches).toBe(1);
	await page.getByRole('button', { name: 'Periksa sesi dan data terbaru', exact: true }).click();
	await expect(page.getByRole('button', { name: 'Simpan draf', exact: true })).toBeEnabled();
	await expect(page.getByLabel('Tujuan pinjaman', { exact: true })).toHaveValue('Tersimpan walau respons terputus');
	expect(patches).toBe(1);
	await page.getByLabel('Filter status', { exact: true }).selectOption('approved');
	await expect(page.getByText('Belum ada pengajuan pada status ini.')).toBeVisible();
	await expect(page.getByRole('button', { name: 'Buat draf pengajuan' })).toHaveCount(0);
	await page.getByLabel('Filter status', { exact: true }).selectOption('');
	await expect(page.getByRole('cell', { name: application.application_number, exact: true })).toBeVisible();
	await mkdir('../docs/validation', { recursive: true });
	await page.screenshot({ path: '../docs/validation/customer-draft-desktop.png', fullPage: true });
	await page.setViewportSize({ width: 320, height: 780 });
	expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
	await page.screenshot({ path: '../docs/validation/customer-draft-mobile-320.png', fullPage: true });
	await page.getByRole('button', { name: 'Hapus draf', exact: true }).click();
	await expect(page.getByRole('dialog')).toBeVisible();
	await page.getByRole('button', { name: 'Batal', exact: true }).click();
	await expect(page.getByRole('dialog')).not.toBeVisible();
	await page.getByRole('button', { name: 'Hapus draf', exact: true }).click();
	const deleted = page.waitForResponse((r) => r.url().endsWith(`/applications/${id}`) && r.request().method() === 'DELETE');
	await page.getByRole('button', { name: 'Ya, hapus draf', exact: true }).click();
	expect((await deleted).status()).toBe(204);
	await expect(page.getByRole('button', { name: 'Buat draf pengajuan' })).toBeEnabled();
	expect(await page.evaluate(async (applicationId) => (await fetch(`http://localhost:8000/api/v1/applications/${applicationId}`, { credentials: 'include', headers: { Accept: 'application/json' } })).status, id)).toBe(404);
});
