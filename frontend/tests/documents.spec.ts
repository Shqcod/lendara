import { expect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { mkdir, readFile } from 'node:fs/promises';

test('dokumen dan pengiriman: versi, batas unggah, tinjau, snapshot dan pemulihan respons tanpa replay', async ({ page }) => {
	test.setTimeout(180000);
	const password = randomUUID();
	await page.goto('/');
	await expect(page.getByText('Belum masuk. Silakan gunakan akun Anda.')).toBeVisible();
	await page.getByRole('button', { name: 'Buat akun', exact: true }).click();
	await page.getByLabel('Nama lengkap').fill('Nasabah Dokumen Fiktif');
	await page.getByLabel('Email', { exact: true }).fill(`document-${randomUUID()}@example.test`);
	await page.getByLabel('Kata sandi', { exact: true }).fill(password);
	await page.getByLabel('Konfirmasi kata sandi').fill(password);
	await page.getByRole('button', { name: 'Daftar akun', exact: true }).click();
	await expect(page.getByText('Pendaftaran berhasil. Silakan masuk.')).toBeVisible();
	await page.getByLabel('Kata sandi', { exact: true }).fill(password);
	await page.getByRole('button', { name: 'Masuk', exact: true }).click();
	await page.getByRole('link', { name: 'Buka ruang nasabah' }).click();
	const created = page.waitForResponse((r) => r.url().endsWith('/applications') && r.request().method() === 'POST');
	await page.getByRole('button', { name: 'Buat draf pengajuan' }).click();
	const application = (await (await created).json()).data;
	const endpoint = `**/api/v1/applications/${application.id}/documents`;
	const panel = page.getByRole('region', { name: 'Dokumen pengajuan', exact: true });
	await expect(panel.getByRole('button', { name: 'Unggah versi baru' })).toBeEnabled();
	await panel.getByLabel('Jenis dokumen', { exact: true }).selectOption({ label: 'D01 · Identitas' });
	const content = Buffer.from('%PDF-1.4\n1 0 obj\n<< /Type /Catalog >>\nendobj\n%%EOF\n');
	const input = panel.getByLabel('Berkas fiktif (PDF, JPG, JPEG, PNG)', { exact: true });
	await input.setInputFiles({ name: 'terlalu-besar.pdf', mimeType: 'application/pdf', buffer: Buffer.alloc(5 * 1024 * 1024 + 1, 32) });
	await panel.getByRole('button', { name: 'Unggah versi baru' }).click();
	await expect(panel.getByText('Ukuran berkas maksimal 5 MB.')).toBeVisible();
	await input.setInputFiles({ name: 'palsu.pdf', mimeType: 'application/pdf', buffer: Buffer.from('Ini bukan PDF.') });
	const invalid = page.waitForResponse((r) => r.url().endsWith('/documents') && r.request().method() === 'POST');
	await panel.getByRole('button', { name: 'Unggah versi baru' }).click();
	expect((await invalid).status()).toBe(422);
	await expect(input).toHaveAttribute('aria-invalid', 'true');

	const maximum = Buffer.alloc(5 * 1024 * 1024, 32); content.copy(maximum);
	await input.setInputFiles({ name: 'identitas-fiktif.pdf', mimeType: 'application/pdf', buffer: maximum });
	const first = page.waitForResponse((r) => r.url().endsWith('/documents') && r.request().method() === 'POST');
	await panel.getByRole('button', { name: 'Unggah versi baru' }).click();
	const firstResponse = await first;
	expect(firstResponse.status()).toBe(201);
	const firstDocument = (await firstResponse.json()).data;
	expect(firstDocument.file_size_bytes).toBe(5 * 1024 * 1024);
	expect(firstDocument.storage_path).toBeUndefined();
	expect(firstResponse.headers()['access-control-allow-credentials']).toBe('true');
	await expect(panel.getByText('Versi 1 · 5120 KB')).toBeVisible();
	await input.setInputFiles({ name: 'identitas-pengganti.pdf', mimeType: 'application/pdf', buffer: content });
	await panel.getByRole('button', { name: 'Unggah versi baru' }).click();
	await expect(panel.getByText(/Versi 2 ·/)).toBeVisible();
	const downloadEvent = page.waitForEvent('download');
	await panel.getByRole('button', { name: 'Unduh D01', exact: true }).click();
	const download = await downloadEvent;
	expect(download.suggestedFilename()).toBe('identitas-pengganti.pdf');
	expect(await readFile((await download.path())!)).toEqual(content);
	const old = await page.evaluate(async (id) => {
		const response = await fetch(`http://localhost:8000/api/v1/document-versions/${id}/download`, { credentials: 'include', headers: { Accept: 'application/json' } });
		return { status: response.status, size: (await response.blob()).size, cache: response.headers.get('cache-control') };
	}, firstDocument.id);
	expect(old).toEqual({ status: 200, size: 5 * 1024 * 1024, cache: 'no-store, private' });

	await input.setInputFiles({ name: 'server-limit.pdf', mimeType: 'application/pdf', buffer: content });
	await page.route(endpoint, async (route) => {
		await route.continue({ postData: Buffer.alloc(9 * 1024 * 1024, 32) });
	}, { times: 1 });
	const oversized = page.waitForResponse((r) => r.url().endsWith('/documents') && r.request().method() === 'POST');
	await panel.getByRole('button', { name: 'Unggah versi baru' }).click();
	const oversizedResponse = await oversized;
	expect(oversizedResponse.status()).toBe(413);
	expect((await oversizedResponse.json()).code).toBe('PAYLOAD_TOO_LARGE');
	await expect(page.getByRole('alert')).toContainText('Unggahan terlalu besar');
	await expect(panel.getByRole('button', { name: 'Unggah versi baru' })).toBeEnabled();

	let posts = 0;
	await input.setInputFiles({ name: 'respons-terputus.pdf', mimeType: 'application/pdf', buffer: content });
	await page.route(endpoint, async (route) => {
		posts++;
		const response = await route.fetch();
		expect(response.status()).toBe(201);
		await route.abort();
	}, { times: 1 });
	await panel.getByRole('button', { name: 'Unggah versi baru' }).click();
	await expect(page.getByRole('alert')).toContainText('Periksa sesi sebelum mengirim ulang');
	await expect(panel.getByRole('button', { name: 'Unggah versi baru' })).toBeDisabled();
	await page.getByRole('button', { name: 'Periksa sesi dan data terbaru', exact: true }).click();
	await expect(panel.getByText(/Versi 3 ·/)).toBeVisible();
	expect(posts).toBe(1);
	await page.reload();
	await expect(panel.getByText('respons-terputus.pdf')).toBeVisible();
	await mkdir('../docs/validation', { recursive: true });
	await panel.screenshot({ path: '../docs/validation/documents-desktop.png' });
	await page.setViewportSize({ width: 320, height: 780 });
	expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
	await expect(panel.getByRole('button', { name: 'Unduh D01', exact: true })).toBeVisible();
	await panel.screenshot({ path: '../docs/validation/documents-mobile-320.png' });

	await page.getByRole('link', { name: 'Tinjau dan lihat pengiriman', exact: true }).click();
	await expect(page).toHaveTitle('Pengiriman Pengajuan | Lendara');
	await expect(page.getByRole('button', { name: 'Tinjau dan kirim', exact: true })).toBeEnabled();
	await page.getByRole('button', { name: 'Tinjau dan kirim', exact: true }).click();
	await expect(page.getByRole('button', { name: 'Ya, kirim pengajuan', exact: true })).toBeDisabled();
	await page.getByRole('button', { name: 'Batal', exact: true }).click();
	await expect(page.getByRole('dialog')).not.toBeVisible();
	await page.getByRole('button', { name: 'Tinjau dan kirim', exact: true }).click();
	await page.getByRole('checkbox').check();
	const incomplete = page.waitForResponse((r) => r.url().endsWith('/submissions') && r.request().method() === 'POST');
	await page.getByRole('button', { name: 'Ya, kirim pengajuan', exact: true }).click();
	expect((await incomplete).status()).toBe(422);
	await expect(page.getByRole('heading', { name: 'Periksa kelengkapan', exact: true })).toBeVisible();
	await expect(page.getByRole('heading', { name: 'Pengiriman versi 1', exact: true })).toHaveCount(0);
	await page.getByRole('link', { name: 'Kembali ke ruang nasabah', exact: true }).click();
	await expect(page.getByRole('button', { name: 'Simpan profil', exact: true })).toBeEnabled();
	await page.getByLabel('NIK fiktif', { exact: true }).fill('000' + Date.now().toString());
	await page.getByLabel('Tanggal lahir', { exact: true }).fill('1995-01-15');
	await page.getByLabel('Nomor kontak fiktif', { exact: true }).fill('+62000000003');
	await page.getByLabel('Jenis pekerjaan', { exact: true }).fill('Karyawan fiktif');
	await page.getByLabel('Tempat bekerja', { exact: true }).fill('Perusahaan Fiktif');
	await page.getByLabel('Lama bekerja (bulan)', { exact: true }).fill('24');
	await page.getByLabel('Alamat fiktif', { exact: true }).fill('Alamat demonstrasi fiktif');
	await page.getByRole('button', { name: 'Simpan profil', exact: true }).click();
	await expect(page.getByText('Profil tersimpan. Data pengiriman sebelumnya tetap dipertahankan.')).toBeVisible();
	await page.getByLabel('Jumlah pinjaman (Rp)', { exact: true }).fill('20000000.01');
	await page.getByLabel('Pendapatan per bulan (Rp)', { exact: true }).fill('8000000');
	await page.getByLabel('Pengeluaran di luar cicilan (Rp)', { exact: true }).fill('3000000');
	await page.getByLabel('Cicilan berjalan per bulan (Rp)', { exact: true }).fill('0');
	await page.getByLabel('Tenor (bulan)', { exact: true }).fill('12');
	await page.getByLabel('Tujuan pinjaman', { exact: true }).fill('Demonstrasi snapshot immutable');
	await page.getByRole('button', { name: 'Simpan draf', exact: true }).click();
	await expect(page.getByText('Draf tersimpan. Pengajuan belum dikirim untuk ditinjau.')).toBeVisible();
	const required = await page.evaluate(async () => {
		const response = await fetch('http://localhost:8000/api/v1/document-types', { credentials: 'include', headers: { Accept: 'application/json' } });
		const types: { id: number; code: string; is_required: boolean; is_active: boolean }[] = (await response.json()).data;
		return types.filter((type) => type.is_required && type.is_active && type.code !== 'D01');
	});
	const nextPanel = page.getByRole('region', { name: 'Dokumen pengajuan', exact: true });
	for (const type of required) {
		await nextPanel.getByLabel('Jenis dokumen', { exact: true }).selectOption(String(type.id));
		await nextPanel.getByLabel('Berkas fiktif (PDF, JPG, JPEG, PNG)', { exact: true }).setInputFiles({ name: `fiktif-${type.code}.pdf`, mimeType: 'application/pdf', buffer: content });
		await nextPanel.getByRole('button', { name: 'Unggah versi baru' }).click();
		await expect(nextPanel.getByRole('button', { name: `Unduh ${type.code}`, exact: true })).toBeEnabled();
	}
	await page.getByRole('link', { name: 'Tinjau dan lihat pengiriman', exact: true }).click();
	await expect(page.getByRole('button', { name: 'Tinjau dan kirim', exact: true })).toBeEnabled();
	await page.getByRole('button', { name: 'Tinjau dan kirim', exact: true }).click();
	await page.getByRole('checkbox').check();
	let sends = 0;
	await page.route(`**/api/v1/applications/${application.id}/submissions`, async (route) => {
		sends++;
		expect(route.request().postDataJSON()).toEqual({ confirmed: true, expected_current_submission_id: null });
		const response = await route.fetch();
		expect(response.status()).toBe(202);
		const result = (await response.json()).data;
		expect(result.version_number).toBe(1); expect(result.anomaly_checks).toBeUndefined(); expect(result.score).toBeUndefined();
		await route.abort();
	}, { times: 1 });
	await page.getByRole('button', { name: 'Ya, kirim pengajuan', exact: true }).click();
	await expect(page.getByRole('alert')).toContainText('Periksa sesi sebelum mengirim ulang');
	await expect(page.getByRole('button', { name: 'Tinjau dan kirim', exact: true })).toBeDisabled();
	await page.getByRole('button', { name: 'Periksa status terbaru', exact: true }).click();
	await expect(page.getByRole('heading', { name: 'Pengiriman versi 1', exact: true })).toBeVisible();
	expect(sends).toBe(1);
	await expect(page.getByRole('button', { name: 'Tinjau dan kirim', exact: true })).toHaveCount(0);
	await expect(page.getByText('Draf → Menunggu verifikasi', { exact: true })).toBeVisible();
	const archivedDownload = page.waitForEvent('download');
	await page.getByRole('button', { name: 'Unduh respons-terputus.pdf', exact: true }).click();
	expect(await readFile((await (await archivedDownload).path())!)).toEqual(content);
	await page.getByRole('link', { name: 'Kembali ke ruang nasabah', exact: true }).click();
	await expect(page.getByRole('button', { name: 'Simpan profil', exact: true })).toBeEnabled();
	await expect(page.getByRole('button', { name: 'Simpan draf', exact: true })).toHaveCount(0);
	await expect(page.getByRole('button', { name: 'Unggah versi baru', exact: true })).toHaveCount(0);
	await page.getByLabel('Nomor kontak fiktif', { exact: true }).fill('+62000000004');
	await page.getByRole('button', { name: 'Simpan profil', exact: true }).click();
	await expect(page.getByText('Profil tersimpan. Data pengiriman sebelumnya tetap dipertahankan.')).toBeVisible();
	await page.getByRole('link', { name: 'Tinjau dan lihat pengiriman', exact: true }).click();
	await expect(page.getByRole('article', { name: 'Pengiriman versi 1', exact: true }).getByText('+62000000003', { exact: true })).toBeVisible();
	await page.reload();
	await expect(page.getByRole('article', { name: 'Pengiriman versi 1', exact: true }).getByText('+62000000003', { exact: true })).toBeVisible();
	expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
	await page.screenshot({ path: '../docs/validation/submission-mobile-320.png', fullPage: true });
	await page.setViewportSize({ width: 1366, height: 900 });
	await page.screenshot({ path: '../docs/validation/submission-desktop.png', fullPage: true });
});
